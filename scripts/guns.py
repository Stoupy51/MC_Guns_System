""" Writes GUNS.md, the list of every gun, from the catalogs the datapack is built from. """
# Imports
import sys
from itertools import groupby
from pathlib import Path

ROOT: Path = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.config.catalogs import GRENADE_TYPES, PRIMARY_WEAPONS, SECONDARY_WEAPONS, SecondaryWeapon, Weapon  # noqa: E402

# Constants
HEADER: str = "| Gun | Id | Magazine | Magazines | In the loadout editor |\n| --- | --- | --- | --- | --- |"
""" Columns of each table. """


# Functions
def table(weapons: list[Weapon] | list[SecondaryWeapon]) -> list[str]:
	return [HEADER, *(
		f"| {w.display_name} | `{w.item_id}` | `{w.magazine_id}` | {w.default_mag_count} | {'Yes' if w.in_loadout else 'No'} |"
		for w in weapons
	), ""]


def main() -> None:
	count = len(PRIMARY_WEAPONS) + len(SECONDARY_WEAPONS)
	lines = ["# Guns", "", f"{count} guns, generated by `scripts/guns.py` from `src/config/catalogs.py`.", ""]
	for category, weapons in groupby(PRIMARY_WEAPONS, key=lambda weapon: weapon.category):
		lines += [f"## {category}", "", *table(list(weapons))]
	lines += ["## Sidearms", "", *table(SECONDARY_WEAPONS)]
	lines += ["## Grenades", "", *(f"- {grenade.display_name}" for grenade in GRENADE_TYPES if grenade.item_id), ""]
	(ROOT / "GUNS.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
	main()

